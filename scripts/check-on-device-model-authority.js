#!/usr/bin/env node
'use strict';

/**
 * ON-DEVICE MODEL AUTHORITY GATE
 *
 * Replaces the blanket "no model asset was added to the repository" rule with
 * a fail-closed, byte-bound allowlist. See config/on-device-model-authority.json
 * for the policy itself and why the blanket rule could not survive Live VTO's
 * approved offline-inference architecture.
 *
 * The posture is DENY. A tracked file whose extension is in the policy's
 * modelAssetExtensions list is a violation unless an approvedModels record
 * names its EXACT path and its sha256 matches the committed bytes. Nothing
 * here can be satisfied by a wildcard, a directory, or a filename alone.
 *
 * `auditModelAssets` is deliberately pure -- it takes the tracked file list,
 * a hashing function, and the authority document, and returns violations. The
 * negative controls exercise it against synthetic fixtures rather than
 * mutating the real working tree, so proving the guard cannot be bypassed
 * never requires temporarily committing a rogue model.
 */

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..');
const AUTHORITY_PATH = 'config/on-device-model-authority.json';
const SHA256_RE = /^[0-9a-f]{64}$/;
const WILDCARD_RE = /[*?[\]]/;

/**
 * Tracked files only. Walking the working tree also walks
 * `modules/.../build`, which is Gradle output full of vendor protobufs --
 * untracked, gitignored, and regenerated by any local compile. "In the
 * repository" is a statement about what git carries, so git is what gets
 * asked. (Reasoning inherited verbatim from the rule this gate supersedes.)
 */
function listTrackedFiles(root = ROOT) {
  return execFileSync('git', ['ls-files'], {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  })
    .split('\n')
    .filter(Boolean);
}

function sha256OfFile(relPath, root = ROOT) {
  return crypto.createHash('sha256').update(fs.readFileSync(path.join(root, relPath))).digest('hex');
}

function isModelAsset(relPath, extensions) {
  const ext = relPath.includes('.') ? relPath.slice(relPath.lastIndexOf('.') + 1).toLowerCase() : '';
  return extensions.includes(ext);
}

/**
 * @param {object} input
 * @param {string[]} input.trackedFiles   every tracked repo-relative path
 * @param {object}   input.authority      parsed config/on-device-model-authority.json
 * @param {(relPath: string) => string} input.hashOf  returns the sha256 of a tracked file
 * @param {(relPath: string) => boolean} [input.exists] defaults to membership in trackedFiles
 * @returns {string[]} violations; empty means PASS
 */
function auditModelAssets({ trackedFiles, authority, hashOf, exists }) {
  const violations = [];

  // ── The authority document itself must be well-formed, or the gate fails
  //    closed rather than silently approving nothing/everything.
  const policy = authority && authority.policy;
  if (!policy || !Array.isArray(policy.modelAssetExtensions) || policy.modelAssetExtensions.length === 0) {
    return [`${AUTHORITY_PATH}: policy.modelAssetExtensions is missing or empty -- the gate cannot know what a model asset is`];
  }
  if (policy.defaultPosture !== 'DENY') {
    violations.push(`${AUTHORITY_PATH}: policy.defaultPosture must be "DENY", got ${JSON.stringify(policy.defaultPosture)}`);
  }
  if (policy.wildcardsAllowed !== false) {
    violations.push(`${AUTHORITY_PATH}: policy.wildcardsAllowed must be false -- approval is per-artifact and byte-bound`);
  }
  const records = Array.isArray(authority.approvedModels) ? authority.approvedModels : null;
  if (!records) {
    return [`${AUTHORITY_PATH}: approvedModels must be an array`];
  }

  const extensions = policy.modelAssetExtensions.map((e) => String(e).toLowerCase());
  const modelFreeModules = Array.isArray(policy.modelFreeModules) ? policy.modelFreeModules : [];
  const fileExists = exists || ((rel) => trackedFiles.includes(rel));

  // ── Every record must be individually valid before it can approve anything.
  const byPath = new Map();
  for (const [i, record] of records.entries()) {
    const where = `${AUTHORITY_PATH} approvedModels[${i}]${record && record.id ? ` (${record.id})` : ''}`;

    if (!record || typeof record.path !== 'string' || record.path.length === 0) {
      violations.push(`${where}: missing a string "path"`);
      continue;
    }
    if (WILDCARD_RE.test(record.path)) {
      violations.push(`${where}: "${record.path}" contains a wildcard -- approval must name one exact artifact`);
      continue;
    }
    if (byPath.has(record.path)) {
      violations.push(`${where}: duplicate authority record for "${record.path}"`);
      continue;
    }
    byPath.set(record.path, record);

    if (record.status !== 'approved') {
      violations.push(`${where}: status must be "approved", got ${JSON.stringify(record.status)}`);
    }
    if (typeof record.sha256 !== 'string' || !SHA256_RE.test(record.sha256)) {
      // A truncated or upper-case digest is a malformed record, not a near-miss:
      // it can never equal a real digest, so it would silently deny forever.
      violations.push(`${where}: sha256 must be 64 lowercase hex characters, got ${JSON.stringify(record.sha256)}`);
    }
    if (record.execution !== 'on_device') {
      violations.push(`${where}: execution must be "on_device", got ${JSON.stringify(record.execution)}`);
    }
    if (record.runtimeDownload !== false) {
      violations.push(`${where}: runtimeDownload must be false -- the approved architecture bundles the model, it never fetches one`);
    }
    if (record.networkInference !== false) {
      violations.push(`${where}: networkInference must be false -- inference is on-device only`);
    }
    for (const field of ['id', 'provider', 'model', 'purpose', 'frameworkLicense', 'modelLicense']) {
      if (typeof record[field] !== 'string' || record[field].length === 0) {
        violations.push(`${where}: missing required provenance field "${field}"`);
      }
    }

    // A record may not authorize a module that is categorically model-free.
    const inModelFreeModule = modelFreeModules.find((prefix) => record.path === prefix || record.path.startsWith(`${prefix}/`));
    if (inModelFreeModule) {
      violations.push(
        `${where}: "${record.path}" is inside model-free module "${inModelFreeModule}" -- ` +
          'that module must use an OS-resident runtime and cannot be authorized a bundled model',
      );
    }

    // A record pointing at nothing is a stale approval; it must not linger.
    if (!fileExists(record.path)) {
      violations.push(`${where}: authorized model "${record.path}" is not tracked in the repository`);
    }
  }

  // ── Every model asset actually present must be approved and byte-identical.
  const present = trackedFiles.filter((rel) => isModelAsset(rel, extensions));
  for (const rel of present) {
    const inModelFreeModule = modelFreeModules.find((prefix) => rel === prefix || rel.startsWith(`${prefix}/`));
    if (inModelFreeModule) {
      violations.push(`${rel}: model asset inside model-free module "${inModelFreeModule}" -- OS-resident runtimes only`);
      continue;
    }
    const record = byPath.get(rel);
    if (!record) {
      violations.push(`${rel}: model asset with no authority record in ${AUTHORITY_PATH}`);
      continue;
    }
    if (typeof record.sha256 !== 'string' || !SHA256_RE.test(record.sha256)) {
      continue; // already reported as malformed above; do not double-report
    }
    let actual;
    try {
      actual = hashOf(rel);
    } catch (error) {
      violations.push(`${rel}: could not be hashed for verification (${error && error.message})`);
      continue;
    }
    if (actual !== record.sha256) {
      violations.push(`${rel}: bytes changed without a governance update -- authority says ${record.sha256}, file is ${actual}`);
    }
  }

  return violations;
}

function auditRepository(root = ROOT) {
  const authority = JSON.parse(fs.readFileSync(path.join(root, AUTHORITY_PATH), 'utf8'));
  const trackedFiles = listTrackedFiles(root);
  return auditModelAssets({
    trackedFiles,
    authority,
    hashOf: (rel) => sha256OfFile(rel, root),
  });
}

module.exports = {
  AUTHORITY_PATH,
  auditModelAssets,
  auditRepository,
  isModelAsset,
  listTrackedFiles,
  sha256OfFile,
};

if (require.main === module) {
  const violations = auditRepository();
  if (violations.length > 0) {
    console.error('ON-DEVICE MODEL AUTHORITY: FAIL');
    for (const v of violations) console.error(`  - ${v}`);
    process.exit(1);
  }
  console.log('ON-DEVICE MODEL AUTHORITY: PASS -- every tracked model asset is explicitly approved and byte-identical.');
}
