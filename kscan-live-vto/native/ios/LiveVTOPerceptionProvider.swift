import Foundation

// MARK: - Frame source

/// Where camera frames for a session originate. Only EMULATOR_CAMERA and
/// SIMULATOR_CAMERA ever produce a live AVCaptureSession frame; a
/// NATIVE_REPLAY_FIXTURE session never opens a camera at all. Evidence
/// generated by this session labels every artifact with the exact case that
/// produced it — never claim EMULATOR_CAMERA or SIMULATOR_CAMERA evidence
/// from a NATIVE_REPLAY_FIXTURE run.
enum FrameSource: String {
  case emulatorCamera = "EMULATOR_CAMERA"
  case simulatorCamera = "SIMULATOR_CAMERA"
  case nativeReplayFixture = "NATIVE_REPLAY_FIXTURE"
}

// MARK: - BodyFrame (mirror of live-vto-contract's bodyFrame.ts)

/// Field-for-field mirror of `@kscan-live-vto/contract`'s `BodyFrame`. Keep
/// this struct's fields in the same order and with the same names as
/// bodyFrame.ts — a native renderer or an evaluation export diffing the two
/// depends on that correspondence being exact, not just "close enough".
struct Point2D: Codable {
  let u: Double
  let v: Double
}

/// Mirrors bodyFrame.ts's `Landmark` discriminated union. Swift has no
/// built-in tagged union with this exact shape, so this uses Codable's
/// keyed-container decoding to accept either `{present: true, point, confidence}`
/// or `{present: false}` — the same two shapes the TypeScript type allows,
/// deliberately not a third "point defaults to origin" case. See
/// bodyFrame.ts's header: "Never substitute a guessed (0,0) or a stale value
/// here."
enum Landmark: Codable {
  case present(point: Point2D, confidence: Double)
  case absent

  private enum CodingKeys: String, CodingKey {
    case present, point, confidence
  }

  init(from decoder: Decoder) throws {
    let container = try decoder.container(keyedBy: CodingKeys.self)
    let isPresent = try container.decode(Bool.self, forKey: .present)
    if isPresent {
      let point = try container.decode(Point2D.self, forKey: .point)
      let confidence = try container.decode(Double.self, forKey: .confidence)
      self = .present(point: point, confidence: confidence)
    } else {
      self = .absent
    }
  }

  func encode(to encoder: Encoder) throws {
    var container = encoder.container(keyedBy: CodingKeys.self)
    switch self {
    case .present(let point, let confidence):
      try container.encode(true, forKey: .present)
      try container.encode(point, forKey: .point)
      try container.encode(confidence, forKey: .confidence)
    case .absent:
      try container.encode(false, forKey: .present)
    }
  }
}

struct BodyFrame: Codable {
  let timestamp: Double

  let headCenter: Landmark
  let noseOrHeadDirection: Landmark
  let neckCenter: Landmark

  let leftShoulder: Landmark
  let rightShoulder: Landmark
  let leftElbow: Landmark
  let rightElbow: Landmark
  let leftWrist: Landmark
  let rightWrist: Landmark

  let chestCenter: Landmark
  let waistCenter: Landmark
  let leftHip: Landmark
  let rightHip: Landmark

  let torsoCenter: Landmark
  let torsoWidth: Double?
  let torsoHeight: Double?
  let torsoRotation: Double?

  let trackingConfidence: Double
}

// MARK: - Perception provider

/// The two-mode adapter Section 4 requires. Neither conforming type below
/// has run in this session — REAL LOCAL MODEL because no device/simulator
/// with a pose runtime is reachable, NATIVE REPLAY PERCEPTION because there
/// is no Swift compiler in this sandbox to build even the replay path
/// against. Both remain TODO/unverified; see native/README.md.
protocol PerceptionProvider {
  var frameSource: FrameSource { get }
  /// Begin producing BodyFrame values via `onFrame`. Never emits a raw
  /// camera frame, mask, or provider-specific landmark ID — only the
  /// vendor-neutral BodyFrame shape above, matching Section 21's "no
  /// downstream package may import provider-specific types" rule extended
  /// to this boundary too.
  func start(onFrame: @escaping (BodyFrame) -> Void, onError: @escaping (Error) -> Void)
  func stop()
}

