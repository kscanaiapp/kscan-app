enum NativeReplayFixtureError: Error {
  case malformedJSON(String)
  case wrongFrameSource(String)
}

/// Consumes the JSON fixture format from
/// packages/evaluation/src/nativeReplayFixture.ts entirely on the native
/// side, per Section 3: "Do not route fixture frames through JS merely
/// because the environment lacks a physical camera." This type never talks
/// to the Expo/React Native bridge — it is constructed and driven from
/// native code, with the fixture bundled as an app resource.
///
/// Structural parsing only. Validation equivalent to
/// `validateNativeReplayFixture` (frameCount match, monotonic timestamps,
/// minimal-pose sanity) has NOT been ported here — this type has never run
/// against a real JSONDecoder, and porting untested validation logic would
/// be worse than porting none, per Section 41's spirit ("port once a device
/// proves the approach is right"). A native implementer should port that
/// function's checks alongside this type's first real test run, not before.
final class NativeReplayPerceptionProvider: PerceptionProvider {
  let frameSource: FrameSource = .nativeReplayFixture
  private let fixtureData: Data
  private var isRunning = false

  init(fixtureData: Data) {
    self.fixtureData = fixtureData
  }

  func start(onFrame: @escaping (BodyFrame) -> Void, onError: @escaping (Error) -> Void) {
    isRunning = true
    do {
      let decoder = JSONDecoder()
      struct Manifest: Codable { let frameSource: String }
      struct Fixture: Codable { let manifest: Manifest; let frames: [BodyFrame] }
      let fixture = try decoder.decode(Fixture.self, from: fixtureData)
      guard fixture.manifest.frameSource == FrameSource.nativeReplayFixture.rawValue else {
        onError(NativeReplayFixtureError.wrongFrameSource(fixture.manifest.frameSource))
        return
      }
      // TODO: real replay would pace these against each frame's timestamp
      // (or the session's declared nominal frame rate) rather than emitting
      // synchronously; timing-accurate replay has not been implemented or
      // measured here.
      for frame in fixture.frames where isRunning {
        onFrame(frame)
      }
    } catch {
      onError(NativeReplayFixtureError.malformedJSON("\(error)"))
    }
  }

  func stop() {
    isRunning = false
  }
}
