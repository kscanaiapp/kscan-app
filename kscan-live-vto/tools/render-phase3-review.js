#!/usr/bin/env node
'use strict';

/**
 * Renders the Phase 3 Section 16 eight-case realism review package.
 *
 * SYNTHETIC/PRECOMPUTED — MECHANICS EVIDENCE ONLY. Every fixture here is
 * authored arithmetic, exactly like Package #2's own fixtures; nothing in
 * this tool runs a real perception or segmentation model, and no real
 * person or retailer image is used. See docs/vto-phase3-visual-review.md.
 *
 * Deterministic: same commit + same fixtures ⇒ byte-identical PNGs. Run from
 * kscan-live-vto/ after building the whole workspace:
 *
 *   npm run build
 *   node tools/render-phase3-review.js
 *
 * Output lands in evidence/phase3-preview/ (a NEW directory -- Package #2's
 * own evidence/static-preview/ is never touched or regenerated by this
 * tool, so its human PASS stays reproducible and undisturbed).
 *
 * Each non-temporal case is rendered TWICE through the real, unmodified
 * `renderRigidStage`/`renderDeformedStage` pipeline: once with no
 * foreground mask (01-static-baseline, i.e. exactly what Package #2's own
 * pipeline already produces) and once with a Phase 3 semantic-occlusion
 * foreground substituted in (02-occlusion-only), proving the Section 6/10
 * seam integrates with the real compositor rather than a parallel one. Every
 * further step (edge diagnostics, gamma/exposure, contact shadow) is then
 * layered onto a clone of that second render's output.
 */

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const R = require('../packages/static-renderer/dist/index.js');
const Realism = require('../packages/realism/dist/index.js');
const RP = require('../packages/realism-preview/dist/index.js');

const OUT_DIR = path.resolve(__dirname, '..', 'evidence', 'phase3-preview');
fs.mkdirSync(OUT_DIR, { recursive: true });

const GIT_SHA = (() => {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: path.resolve(__dirname, '..', '..') })
      .toString()
      .trim();
  } catch {
    return 'unknown';
  }
})();

function writePng(name, image) {
  const file = path.join(OUT_DIR, `${name}.png`);
  fs.writeFileSync(file, R.encodePng(image));
  return { file: path.basename(file), bytes: fs.statSync(file).size, width: image.width, height: image.height };
}

function writeJson(name, value) {
  const file = path.join(OUT_DIR, `${name}.json`);
  fs.writeFileSync(file, JSON.stringify(value, null, 2) + '\n');
  return path.basename(file);
}

const EVIDENCE_CLASS = 'SYNTHETIC/PRECOMPUTED — MECHANICS EVIDENCE ONLY';

// ─── Semantic scene helpers (fractions of the actual render dimensions) ────

function fractionalSemanticFrame(region, width, height, frac, confidence) {
  const mask = Realism.createMask(width, height, 0);
  Realism.fillRect(
    mask,
    { x: frac.x * width, y: frac.y * height, w: frac.w * width, h: frac.h * height },
    1,
  );
  return {
    region,
    frame: { timestamp: 0, mask, confidence, provenance: 'PRECOMPUTED' },
    label: Realism.PRECOMPUTED_SEMANTIC_MASK_LABEL,
  };
}

const SCENE_BUILDERS = {
  none: () => ({}),
  oneForearmCrossingChest: (w, h) => ({
    forearm_hand: fractionalSemanticFrame('forearm_hand', w, h, { x: 0.26, y: 0.4, w: 0.48, h: 0.1 }, 0.9),
  }),
  bothArmsInteractingWithTorso: (w, h) => ({
    forearm_hand: fractionalSemanticFrame('forearm_hand', w, h, { x: 0.26, y: 0.4, w: 0.48, h: 0.1 }, 0.88),
    upper_arm: fractionalSemanticFrame('upper_arm', w, h, { x: 0.16, y: 0.3, w: 0.13, h: 0.28 }, 0.86),
  }),
  hairOverShoulder: (w, h) => ({
    hair: fractionalSemanticFrame('hair', w, h, { x: 0.6, y: 0.1, w: 0.16, h: 0.36 }, 0.82),
  }),
};

