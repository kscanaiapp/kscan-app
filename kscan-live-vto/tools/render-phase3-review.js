// ─── Cases (Section 16) ──────────────────────────────────────────────────────

const CASES = [
  { caseId: 'case-1-neutral-plain-tee', title: 'CASE 1 — NEUTRAL POSE, PLAIN TEE', person: personSpecs.neutral, garment: plainTee, scene: 'none' },
  { caseId: 'case-2-logo-tee-canary', title: 'CASE 2 — LOGO/TEXT TEE (CANARY)', person: personSpecs.neutral, garment: logoTee, scene: 'none', isCanary: true },
  { caseId: 'case-3-forearm-crossing', title: 'CASE 3 — FOREARM CROSSING', person: personSpecs.crossed, garment: plainTee, scene: 'oneForearmCrossingChest' },
  { caseId: 'case-4-both-arms-torso', title: 'CASE 4 — BOTH ARMS INTERACTING WITH TORSO', person: personSpecs.bothArms, garment: plainTee, scene: 'bothArmsInteractingWithTorso' },
  { caseId: 'case-5-hair-over-shoulder', title: 'CASE 5 — HAIR-OVER-SHOULDER SEMANTIC CASE', person: personSpecs.hairCase, garment: plainTee, scene: 'hairOverShoulder' },
  { caseId: 'case-7-dark-scene-light-garment', title: 'CASE 7 — LIGHTING MISMATCH: DARK SCENE / LIGHT GARMENT', person: personSpecs.darkScene, garment: lightTee, scene: 'none', isLightingCase: true },
  { caseId: 'case-8-bright-scene-dark-garment', title: 'CASE 8 — LIGHTING MISMATCH: BRIGHT SCENE / DARK GARMENT', person: personSpecs.brightScene, garment: darkTee, scene: 'none', isLightingCase: true },
];

function buildInput(personFixture, garmentFixture, testCase, foregroundMask, maskProvenance) {
  return {
    fixtureId: personFixture.spec.fixtureId,
    caseId: testCase.caseId,
    personImage: personFixture.image,
    bodyFrame: personFixture.bodyFrame,
    descriptor: testCase.garment.descriptor,
    asset: assetOf(testCase.garment),
    foregroundMask,
    maskProvenance,
    gitSha: GIT_SHA,
    knownLimitations: [EVIDENCE_CLASS],
  };
}

const summary = {
  generatedFrom: { gitSha: GIT_SHA, rendererVersion: R.RENDERER_VERSION, deformationAlgorithm: R.DEFORMATION_ALGORITHM },
  evidenceClass: EVIDENCE_CLASS,
  segmentationEngine: 'NOT YET IMPLEMENTED — PRECOMPUTED TEST MASKS ONLY, SEE docs/vto-phase3-native-blockers.md',
  baselineNote:
    "'01-static-baseline' already carries Package #2's existing gain-based lighting adjustment (Phase 1-2, unchanged). "
    + "'04-lighting-adjusted' layers Phase 3's NEW gamma/exposure control on top of that, not a replacement for it.",
  cases: [],
  temporalCases: [],
};

for (const testCase of CASES) {
  const person = R.generateSyntheticPerson(testCase.person);
  const record = { caseId: testCase.caseId, title: testCase.title, garment: testCase.garment.manifest.productId, images: {} };

  // 01 — static baseline: no Phase 3 involvement at all.
  const baselineInput = buildInput(person, testCase.garment, testCase, null, 'none');
  const baselineRigid = R.renderRigidStage(baselineInput);
  if (!baselineRigid.ok) {
    record.status = 'FAILED_BEFORE_RIGID';
    record.failure = { stage: baselineRigid.stage, reason: baselineRigid.reason };
    summary.cases.push(record);
    console.error(`[${testCase.caseId}] FAILED at ${baselineRigid.stage}: ${baselineRigid.reason}`);
    continue;
  }
  const baselineDeformed = R.renderDeformedStage(baselineInput, baselineRigid.result);
  if (!baselineDeformed.ok) {
    record.status = 'STOPPED_AT_RIGID_GATE';
    record.failure = { reason: baselineDeformed.reason, findings: baselineDeformed.gate.findings };
    summary.cases.push(record);
    console.error(`[${testCase.caseId}] STOP GATE: ${baselineDeformed.gate.findings.join(', ')}`);
    continue;
  }

  record.images.source = writePng(`${testCase.caseId}-00-person-fixture`, person.image);
  record.images.staticBaseline = writePng(`${testCase.caseId}-01-static-baseline`, baselineDeformed.result.image);
  record.rigidGate = baselineRigid.result.gate;

  // 02 — occlusion-only: same pipeline, Phase 3 semantic foreground substituted.
  const sceneBuilder = SCENE_BUILDERS[testCase.scene];
  const scene = sceneBuilder(person.image.width, person.image.height);
  const { image: semanticForeground, contributingRegions } = RP.semanticSceneToForegroundImage(scene, person.image);
  const occlusionInput = buildInput(person, testCase.garment, testCase, semanticForeground, 'precomputed');
  const occlusionRigid = R.renderRigidStage(occlusionInput);
  const occlusionDeformed = occlusionRigid.ok ? R.renderDeformedStage(occlusionInput, occlusionRigid.result) : null;
  const occlusionImage = occlusionDeformed && occlusionDeformed.ok ? occlusionDeformed.result.image : baselineDeformed.result.image;
  record.images.occlusionOnly = writePng(`${testCase.caseId}-02-occlusion-only`, occlusionImage);
  record.semanticScene = {
    contributingRegions,
    label: contributingRegions.length > 0 ? Realism.PRECOMPUTED_SEMANTIC_MASK_LABEL : 'n/a — no region populated for this case',
  };

  // 03 — edge-improved: Phase 3 adds only measurement here (Package #2's
  // existing GARMENT_SUPERSAMPLE=2 premultiplied-alpha compositing already
  // produces the soft edge), so the pixels are identical to 02 -- not
  // duplicated as a file, only diagnosed and referenced.
  const edgeHistogramBaseline = RP.alphaCoverageHistogram(baselineDeformed.result.garmentLayer);
  const edgeHistogramOcclusion = RP.alphaCoverageHistogram(occlusionImage);
  record.images.edgeImproved = { sameAs: '02-occlusion-only', note: 'Phase 3 adds edge diagnostics only; see edgeDiagnostics below.' };
  record.edgeDiagnostics = {
    garmentLayerAlphaHistogram: edgeHistogramBaseline,
    garmentLayerEdgePartialAlphaRatio: RP.edgePartialAlphaRatio(edgeHistogramBaseline),
    finalCompositeOpaqueBoundingBox: RP.opaqueBoundingBox(occlusionImage),
  };

  // 04 — lighting-adjusted: Phase 3 gamma/exposure on a clone of 02.
  const lightingImage = R.cloneImage(occlusionImage);
  const gammaAdjustment = RP.computeGammaExposureAdjustment(
    { meanLuminance: baselineDeformed.result.manifest.lightingParameters.state.meanLuminance },
    RP.meanLuminanceOfOpaquePixels(baselineDeformed.result.garmentLayer),
  );
  RP.applyGammaExposureAdjustment(lightingImage, gammaAdjustment);
  record.images.lightingAdjusted = writePng(`${testCase.caseId}-04-lighting-adjusted`, lightingImage);
  record.gammaExposureAdjustment = gammaAdjustment;

  // 05/06 — shadow-adjusted / final P3 composite: same pixels; 06 is the
  // canonical written file (the section's "final P3 composite" deliverable).
  const finalImage = R.cloneImage(lightingImage);
  const shoulderSpan = {
    leftX: baselineRigid.result.anchors.leftShoulder.x,
    rightX: baselineRigid.result.anchors.rightShoulder.x,
    topY: Math.min(baselineRigid.result.anchors.leftShoulder.y, baselineRigid.result.anchors.rightShoulder.y),
  };
  const shadowRegions = RP.standardCollarAndShoulderShadowRegions(shoulderSpan);
  RP.applyContactShadows(finalImage, shadowRegions);
  record.images.finalP3Composite = writePng(`${testCase.caseId}-06-final-p3-composite`, finalImage);
  record.images.shadowAdjusted = { sameAs: '06-final-p3-composite' };
  record.shadowRegions = shadowRegions;

  // 07 — diagnostic overlay: reuse the existing annotated rigid overlay.
  record.images.diagnosticOverlay = writePng(`${testCase.caseId}-07-diagnostic-overlay`, baselineRigid.result.overlay);

  // Product fidelity + color fidelity.
  const sampleX = Math.round(person.image.width / 2);
  const sampleY = Math.round(person.image.height * 0.55);
  const before = RP.samplePixelColor(baselineDeformed.result.image, sampleX, sampleY);
  const after = RP.samplePixelColor(finalImage, sampleX, sampleY);
  record.productFidelity = {
    logoCanary: testCase.isCanary ? baselineDeformed.result.metrics.logo : null,
    sampledColor: { before, after },
    hueDeltaDegrees: RP.hueDeltaDegrees(before, after),
    preservesChannelBrightness80pct: RP.preservesChannelBrightness(before, after, 0.8),
    silhouetteUnchanged: JSON.stringify(RP.opaqueBoundingBox(baselineDeformed.result.image)) === JSON.stringify(RP.opaqueBoundingBox(finalImage)),
  };
  record.foregroundOverGarmentPixels = occlusionDeformed && occlusionDeformed.ok ? occlusionDeformed.result.metrics.foregroundOverGarmentPixels : null;

  record.manifestFile = writeJson(`${testCase.caseId}-manifest`, {
    evidenceClass: EVIDENCE_CLASS,
    caseId: testCase.caseId,
    title: testCase.title,
    baseManifest: baselineDeformed.result.manifest,
    semanticScene: record.semanticScene,
    edgeDiagnostics: record.edgeDiagnostics,
    gammaExposureAdjustment: record.gammaExposureAdjustment,
    shadowRegions: record.shadowRegions,
    productFidelity: record.productFidelity,
    foregroundOverGarmentPixels: record.foregroundOverGarmentPixels,
  });

  record.status = 'RENDERED';
  summary.cases.push(record);
  console.log(
    `[${testCase.caseId}] rendered  gate=${baselineRigid.result.gate.passed ? 'PASS' : 'FAIL'}`
      + `  gamma=${gammaAdjustment.gamma.toFixed(3)}`
      + `  hueDelta=${record.productFidelity.hueDeltaDegrees.toFixed(2)}deg`
      + `  brightnessOk=${record.productFidelity.preservesChannelBrightness80pct}`
      + `  silhouetteUnchanged=${record.productFidelity.silhouetteUnchanged}`,
  );
}

// ─── Case 6 — mask instability/dropout: temporal, contact-sheet artifact ────

function maskToTile(mask, scale, borderRgb) {
  const w = mask.width * scale;
  const h = mask.height * scale;
  const tile = R.createImage(w + 4, h + 4, R.rgba(borderRgb[0], borderRgb[1], borderRgb[2], 255));
  for (let y = 0; y < mask.height; y += 1) {
    for (let x = 0; x < mask.width; x += 1) {
      const v = Math.round((mask.coverage[y * mask.width + x] || 0) * 255);
      for (let sy = 0; sy < scale; sy += 1) {
        for (let sx = 0; sx < scale; sx += 1) {
          R.setPixel(tile, 2 + x * scale + sx, 2 + y * scale + sy, R.rgba(v, v, v, 255));
        }
      }
    }
  }
  return tile;
}

function borderColorFor(frame) {
  if (frame.failedSafe) return [200, 40, 40]; // red
  if (frame.held) return [220, 160, 30]; // amber
  return [40, 170, 90]; // green
}

{
  const rawSequence = Realism.maskDropoutSequence(4, 1, 4);
  const stabilized = Realism.stabilizeSequence(rawSequence);
  const scale = 4;
  const tiles = stabilized.map((f) => maskToTile(f.mask, scale, borderColorFor(f)));
  const tileWidth = tiles[0].width;
  const tileHeight = tiles[0].height;
  const sheet = R.createImage(tileWidth * tiles.length, tileHeight, R.rgba(255, 255, 255, 255));
  tiles.forEach((tile, i) => {
    for (let y = 0; y < tileHeight; y += 1) {
      for (let x = 0; x < tileWidth; x += 1) {
        R.setPixel(sheet, i * tileWidth + x, y, R.getPixel(tile, x, y));
      }
    }
  });

  const caseId = 'case-6-mask-instability-dropout';
  const contactSheet = writePng(`${caseId}-contact-sheet`, sheet);
  const rates = Realism.temporalMaskChangeRate(rawSequence);
  const recoveryFrames = Realism.maskDropRecoveryFrames(stabilized);

  const manifestFile = writeJson(`${caseId}-manifest`, {
    evidenceClass: EVIDENCE_CLASS,
    caseId,
    title: 'CASE 6 — MASK INSTABILITY / DROPOUT SEQUENCE (TEMPORAL)',
    note:
      'Temporal case per Section 17: no single source frame applies. Legend: green border = trusted/live frame, '
      + 'amber = held (frozen/blended, within budget), red = failedSafe (held past the budget, decaying). '
      + 'Sequence: 4 good frames, 1 dropout frame, 4 recovery frames (maskDropoutSequence(4,1,4)), default MaskStabilityConfig.',
    frameCount: stabilized.length,
    frames: stabilized.map((f, i) => ({
      index: i,
      timestamp: f.timestamp,
      rawConfidence: f.rawConfidence,
      effectiveConfidence: f.effectiveConfidence,
      trusted: f.trusted,
      held: f.held,
      holdFramesUsed: f.holdFramesUsed,
      failedSafe: f.failedSafe,
    })),
    metrics: {
      temporalMaskChangeRate: rates,
      temporalMaskChangeRateSummary: Realism.summarizeDistribution(rates),
      maskDropRecoveryFrames: recoveryFrames,
    },
  });

  summary.temporalCases.push({ caseId, title: 'CASE 6 — MASK INSTABILITY / DROPOUT SEQUENCE (TEMPORAL)', contactSheet, manifestFile });
  console.log(`[${caseId}] rendered  frames=${stabilized.length}  recoveryEpisodes=${JSON.stringify(recoveryFrames)}`);
}

